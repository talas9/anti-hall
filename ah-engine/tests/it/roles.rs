//! Owner feature 22: the generated `anti-hall:engine` skill family cannot go stale or bloat, and the role matrix is enforced.
//! The skills are compared with the committed files (regenerate with `scripts/gen-engine-skills.sh`), each is held to its size
//! budget, every implemented verb has a matrix row, each role's allowed and refused verbs are checked on the command line and in
//! the PreToolUse guard, the role is detected for every kind of caller, and the injected note is capped and per role.
#![allow(clippy::unwrap_used, clippy::expect_used)] // a test crate: a panic is the failure report, and E2 exempts tests

use ah_engine::reqenv::RequestEnv;
use ah_engine::{roles, skillgen};
use serde_json::{Value, json};
use std::io::Write;
use std::path::PathBuf;
use std::process::{Command, Stdio};

fn plugin() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../plugins/anti-hall")
}

fn args(a: &[&str]) -> Vec<String> {
    a.iter().map(|s| s.to_string()).collect()
}

#[test]
fn the_committed_skills_equal_the_generated_ones_for_both_hosts() {
    assert_eq!(skillgen::hosts().len(), 2, "Claude and Codex");
    for host in skillgen::hosts() {
        for s in skillgen::family(host) {
            let committed = std::fs::read_to_string(plugin().join(&s.path)).unwrap_or_default();
            assert!(
                committed == s.text,
                "{} is stale: run ah-engine/scripts/gen-engine-skills.sh and commit ({} bytes committed, {} generated)",
                s.path,
                committed.len(),
                s.text.len()
            );
        }
    }
}

#[test]
fn no_committed_engine_skill_is_outside_the_generated_family() {
    for host in skillgen::hosts() {
        let family = skillgen::family(host);
        let (dir, prefix) = if host == "codex" { ("codex/skills", "anti-hall-engine") } else { ("skills", "engine") };
        for e in std::fs::read_dir(plugin().join(dir)).unwrap().flatten() {
            let n = e.file_name().to_string_lossy().to_string();
            if n.starts_with(prefix) {
                assert!(
                    family.iter().any(|s| s.path == format!("{dir}/{n}/SKILL.md")),
                    "{dir}/{n} is not generated by the registry (an area was emptied or renamed)"
                );
            }
        }
    }
}

#[test]
fn every_skill_is_within_its_size_budget_and_the_main_one_is_tiny() {
    for host in skillgen::hosts() {
        for s in skillgen::family(host) {
            assert!(
                s.text.len() <= skillgen::budget(&s),
                "{} is {} bytes, over its {} byte budget (roles.skill_budget): split the area",
                s.path,
                s.text.len(),
                skillgen::budget(&s)
            );
        }
    }
    let main = skillgen::family("claude").remove(0);
    assert!(main.main && main.text.len() < 4000);
}

#[test]
fn every_skill_has_a_use_when_description_and_the_main_one_points_at_every_area() {
    for host in skillgen::hosts() {
        let fam = skillgen::family(host);
        for s in &fam {
            let d = s.text.lines().find(|l| l.starts_with("description: ")).unwrap();
            assert!(d.starts_with("description: \"Use when "), "{}: {d}", s.path);
            assert!(s.text.lines().nth(1).unwrap().starts_with("name: "));
        }
        for s in fam.iter().filter(|s| !s.main) {
            assert!(fam[0].text.contains(&format!("`{}`", skillgen_ref(host, &s.name))), "the main skill does not point at {}", s.name);
        }
    }
}

fn skillgen_ref(host: &str, name: &str) -> String {
    let bare = name.trim_start_matches("anti-hall-");
    if host == "codex" { format!("$anti-hall-{bare}") } else { format!("/anti-hall:{bare}") }
}

#[test]
fn the_codex_family_has_the_same_areas_and_the_same_verbs_as_the_claude_one() {
    let strip = |name: &str| name.trim_start_matches("anti-hall-").to_string();
    let a: Vec<String> = skillgen::family("claude").iter().map(|s| strip(&s.name)).collect();
    let b: Vec<String> = skillgen::family("codex").iter().map(|s| strip(&s.name)).collect();
    assert_eq!(a, b);
    let verbs = |host: &str| -> Vec<String> {
        skillgen::family(host)
            .iter()
            .flat_map(|s| {
                s.text.lines().filter(|l| l.starts_with("| `ah-engine ")).map(|l| l.split('|').nth(1).unwrap().trim().to_string()).collect::<Vec<_>>()
            })
            .collect()
    };
    assert_eq!(verbs("claude"), verbs("codex"));
}

#[test]
fn every_implemented_verb_has_a_matrix_row_in_a_known_area_and_no_row_is_orphaned() {
    let implemented: Vec<String> = ah_engine::cli::commands().into_iter().filter(|c| c.status == "implemented").map(|c| c.name).collect();
    for v in &implemented {
        let r = roles::row(v).unwrap_or_else(|| panic!("verb {v} has no roles.matrix row: declare which roles may use it"));
        assert!(!r.roles.is_empty(), "{v}");
        for x in r.roles.iter().chain(&r.self_only) {
            assert!(roles::names().contains(x), "{v}: unknown role {x}");
        }
    }
    for v in roles::verbs() {
        assert!(implemented.iter().any(|i| i == v), "roles.matrix names {v}, which is not an implemented command");
    }
    for c in ah_engine::checks::registry() {
        assert!(!skillgen::check_area(c.name()).is_empty());
    }
}

#[test]
fn the_default_matrix_keeps_owner_level_verbs_for_the_main_session() {
    for v in ["restore", "stop", "ctl", "serve", "reset", "maintain", "backup", "migrate", "jev-setup", "jev_sweep"] {
        let r = roles::row(v).unwrap();
        assert!(!r.roles.contains(&"subagent") && !r.roles.contains(&"workspace"), "{v} must not be open to subagents or workspace children");
    }
    for v in ["version", "status", "metrics", "impact", "docs", "check"] {
        assert!(roles::row(v).unwrap().roles.contains(&"subagent"), "{v} is a read verb every role may use");
    }
    let mesh = roles::row("mesh").unwrap();
    assert_eq!(mesh.self_only, vec!["workspace"]);
}

