#[test]
fn the_command_line_role_comes_from_the_environment_and_a_declaration_only_narrows() {
    assert_eq!(roles::role_from_env(&env(&[("HOME", "/h")])), "main");
    assert_eq!(roles::role_from_env(&env(&[("HOME", "/h"), ("DEVSWARM_SOURCE_BRANCH", "feat/x")])), "workspace");
    assert_eq!(roles::role_from_env(&env(&[("HOME", "/h"), ("DEVSWARM_SOURCE_BRANCH", "")])), "main", "a Primary has an empty branch");
    assert_eq!(roles::role_from_env(&env(&[("HOME", "/h"), ("ANTIHALL_ROLE", "subagent")])), "subagent");
    assert_eq!(roles::role_from_env(&env(&[("HOME", "/h"), ("ANTIHALL_ROLE", "codex")])), "codex");
    assert_eq!(
        roles::role_from_env(&env(&[("HOME", "/h"), ("DEVSWARM_SOURCE_BRANCH", "b"), ("ANTIHALL_ROLE", "main")])),
        "workspace",
        "a declaration never widens"
    );
    assert_eq!(roles::role_from_env(&env(&[("HOME", "/h"), ("ANTIHALL_ROLE", "nonsense")])), "main");
}

#[test]
fn each_role_runs_what_the_matrix_allows_and_is_refused_the_rest_with_who_may() {
    let e = env(&[("HOME", "/h"), ("DEVSWARM_BUILDER_ID", "ws-1")]);
    // main and the Codex main seat run owner-level verbs
    for role in ["main", "codex"] {
        for v in ["restore", "stop", "jev-setup", "mesh", "status"] {
            assert!(roles::check(role, v, &[], &e).is_ok(), "{role} {v}");
        }
    }
    // a subagent: read verbs yes, owner-level no, owner args no
    assert!(roles::check("subagent", "status", &[], &e).is_ok());
    assert!(roles::check("subagent", "doctor", &args(&["--check"]), &e).is_ok());
    let m = roles::check("subagent", "restore", &args(&["snap"]), &e).unwrap_err();
    assert!(m.contains("`restore`") && m.contains("subagent") && m.contains("main") && m.contains("codex"), "{m}");
    let m = roles::check("subagent", "doctor", &args(&["--repair"]), &e).unwrap_err();
    assert!(m.contains("reserved for the main session"), "{m}");
    assert!(roles::check("main", "doctor", &args(&["--repair"]), &e).is_ok());
    assert!(roles::check("subagent", "proj", &args(&["/x", "put"]), &e).is_err(), "a subagent has no project mailbox");
    // a workspace child: itself only
    assert!(roles::check("workspace", "mesh", &args(&["read", "--id", "ws-1"]), &e).is_ok());
    let m = roles::check("workspace", "mesh", &args(&["read", "--id", "ws-2"]), &e).unwrap_err();
    assert!(m.contains("ws-2") && m.contains("ws-1"), "{m}");
    assert!(roles::check("workspace", "mesh", &args(&["roster"]), &e).is_ok());
    assert!(roles::check("workspace", "stop", &[], &e).is_err());
    assert!(roles::check("workspace", "config", &args(&["heal"]), &e).is_err());
    assert!(roles::check("workspace", "config", &[], &e).is_ok());
    // a verb the matrix does not know is not this module's to judge
    assert!(roles::check("subagent", "no-such-verb", &[], &e).is_ok());
}

/// Run the built binary with a clean environment.
fn run(argv: &[&str], extra: &[(&str, &str)], stdin: &str) -> (i32, String, String) {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(format!("roles-{}", std::process::id()));
    std::fs::create_dir_all(dir.join("home")).unwrap();
    let mut c = Command::new(env!("CARGO_BIN_EXE_ah-engine"));
    c.args(argv)
        .env_clear()
        .env("PATH", std::env::var("PATH").unwrap_or_default())
        .env("HOME", dir.join("home"))
        .env("AH_ENGINE_DIR", dir.join("state"))
        .env("AH_ENGINE_NOSPAWN", "1")
        .env("AH_ENGINE_PLUGIN_ROOT", plugin())
        .current_dir(&dir)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    c.envs(extra.iter().copied());
    let mut ch = c.spawn().unwrap();
    ch.stdin.take().unwrap().write_all(stdin.as_bytes()).unwrap();
    let o = ch.wait_with_output().unwrap();
    (o.status.code().unwrap_or(-1), String::from_utf8_lossy(&o.stdout).to_string(), String::from_utf8_lossy(&o.stderr).to_string())
}

#[test]
fn the_command_line_refuses_a_workspace_child_an_owner_verb_and_a_sibling() {
    let ws = [("DEVSWARM_SOURCE_BRANCH", "feat/x"), ("DEVSWARM_BUILDER_ID", "ws-1")];
    let (code, _, err) = run(&["restore", "nowhere"], &ws, "");
    assert_eq!(code, 77, "{err}");
    assert!(err.contains("not available to workspace sessions") && err.contains("main"), "{err}");
    let (code, out, _) = run(&["--json", "stop"], &ws, "");
    assert_eq!(code, 77);
    assert!(out.contains("\"error\""), "{out}");
    let (code, _, err) = run(&["mesh", "read", "--db", "/nonexistent/x.db", "--id", "ws-2"], &ws, "");
    assert_eq!(code, 77, "{err}");
    assert!(err.contains("may only act on itself"), "{err}");
    // a read verb is open to it, and the main session is not gated
    assert_eq!(run(&["version"], &ws, "").0, 0);
    assert_eq!(run(&["version"], &[], "").0, 0);
    // the switch: off lets the child run it (the verb itself then fails on its own terms, not with the role exit)
    let off = [("DEVSWARM_SOURCE_BRANCH", "feat/x"), ("ANTIHALL_ROLE_GUARD", "0")];
    assert_ne!(run(&["restore", "nowhere"], &off, "").0, 77);
}

fn payload(event: &str, extra: Value) -> String {
    let mut p = json!({"session_id": "s1", "cwd": "/tmp", "hook_event_name": event});
    for (k, v) in extra.as_object().unwrap() {
        p[k] = v.clone();
    }
    p.to_string()
}

fn note(extra: Value, env_pairs: &[(&str, &str)], event: &str) -> String {
    let (code, out, err) = run(&["check", "engine-role-note"], env_pairs, &payload(event, extra));
    assert_eq!(code, 0, "{err}");
    let v: Value = serde_json::from_str(out.trim()).unwrap_or_else(|_| panic!("no note: {out:?} {err}"));
    v["hookSpecificOutput"]["additionalContext"].as_str().unwrap().to_string()
}

#[test]
fn the_role_note_names_the_role_lists_only_what_it_may_use_and_points_at_the_main_skill() {
    let main = note(json!({}), &[], "SessionStart");
    let ws = note(json!({}), &[("DEVSWARM_SOURCE_BRANCH", "b")], "SessionStart");
    let sub = note(json!({"agent_id": "a1", "agent_type": "general-purpose"}), &[], "SubagentStart");
    let codex = note(json!({"turn_id": "t1", "model": "gpt"}), &[], "SessionStart");
    for (n, role) in [(&main, "main"), (&ws, "workspace"), (&sub, "subagent"), (&codex, "codex")] {
        assert!(n.contains(&format!("(role: {role})")), "{role}: {n}");
        assert!(n.chars().count() <= ah_engine::defaults::num("roles.note_max") as usize, "{role}: {} chars", n.chars().count());
        assert!(n.len() < 10_000, "inside the hook injection cap");
    }
    assert!(main.contains("restore") && main.contains("jev-setup"));
    assert!(!sub.contains("restore") && !sub.contains("proj") && sub.contains("status"), "{sub}");
    assert!(!ws.contains("restore") && ws.contains("proj") && ws.contains("mesh"), "{ws}");
    assert!(main.contains("/anti-hall:engine") && !main.contains("engine-"), "points at the main skill only: {main}");
    assert!(sub.contains("/anti-hall:engine"));
    assert!(codex.contains("$anti-hall-engine") && !codex.contains("/anti-hall:"), "{codex}");
}

