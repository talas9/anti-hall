#[test]
fn date_parse_agrees_with_v8_wherever_it_decides() {
    let (mut decided, mut total) = (0, 0);
    for (s, want) in DATES {
        total += 1;
        match (date_parse(s), want) {
            (DateParse::Ms(got), Some(w)) => {
                assert_eq!(got, *w, "{s:?}");
                decided += 1;
            }
            (DateParse::Nan, None) => decided += 1,
            (DateParse::Unsupported, _) => {}
            (got, want) => panic!("{s:?}: got {got:?}, V8 says {want:?}"),
        }
    }
    assert!(decided * 100 >= total * 70, "the strict ISO form must be decided, not deferred: {decided}/{total}");
}

#[test]
fn date_parse_never_decides_a_form_it_does_not_own() {
    for s in ["2026-10-06T10:00:00", "2026-10-06", "2026-10-06 10:00:00Z", "2026-10-06T10:00:00z", "1700000000000", "Tue Oct 06 2026", "", "x", "2026-10-06T10:00Z", "+002026-10-06T10:00:00Z"] {
        assert_eq!(date_parse(s), DateParse::Unsupported, "{s:?}");
    }
}

#[test]
fn number_to_string_is_ecmascript() {
    for (n, want) in NUMS {
        assert_eq!(number_to_string(*n), *want, "{n:e}");
    }
    assert_eq!(number_to_string(f64::NAN), "NaN");
    assert_eq!(number_to_string(-0.0), "0");
}

#[test]
fn to_number_is_number_of_a_trimmed_string() {
    for (s, want) in TONUM {
        let got = to_number(s);
        match want {
            Some(w) => assert_eq!(got, *w, "{s:?}"),
            None => assert!(got.is_nan(), "{s:?} gave {got}"),
        }
    }
}

#[test]
fn json_round_trip_keeps_javascript_key_order_and_escapes() {
    for (src, want) in OBJS {
        // `1e21` and the like are numbers JSON.stringify prints in its own way; the table has Node's text
        let got = Js::parse(src).unwrap().stringify();
        assert_eq!(got, *want, "{src}");
    }
}

#[test]
fn lone_surrogate_escapes_become_the_replacement_character_and_pairs_survive() {
    assert_eq!(fix_lone_surrogates("\"a\\ud83d b\"").as_ref(), "\"a\\uFFFD b\"");
    assert_eq!(fix_lone_surrogates("\"\\udc00\"").as_ref(), "\"\\uFFFD\"");
    assert_eq!(fix_lone_surrogates("\"\\ud83d\\ude00\"").as_ref(), "\"\\ud83d\\ude00\"");
    assert_eq!(fix_lone_surrogates("\"\\\\ud83d\"").as_ref(), "\"\\\\ud83d\"", "an escaped backslash is not an escape");
    assert_eq!(fix_lone_surrogates("\"\\ud83d\\u0041\"").as_ref(), "\"\\uFFFD\\u0041\"");
    assert_eq!(fix_lone_surrogates("no escapes").as_ref(), "no escapes");
    assert!(parse_line("{\"a\":\"x\\ud800y\"}").is_some());
    assert!(parse_line("{\"a\":").is_none());
}

#[test]
fn only_canonical_array_indexes_sort_first() {
    let j = Js::parse("{\"b\":1,\"10\":2,\"2\":3,\"01\":4,\"a\":5,\"4294967295\":6}").unwrap();
    assert_eq!(j.stringify(), "{\"2\":3,\"10\":2,\"b\":1,\"01\":4,\"a\":5,\"4294967295\":6}");
}

#[test]
fn a_duplicate_key_keeps_its_first_position_and_its_last_value() {
    assert_eq!(Js::parse("{\"a\":1,\"b\":2,\"a\":3}").unwrap().stringify(), "{\"a\":3,\"b\":2}");
}
