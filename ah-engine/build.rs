//! Collects the settings keys this build reads, so a plugin whose defaults lack one is rejected when the engine loads
//! them (a plugin and an engine of different versions) instead of panicking later in a hook call.
//!
//! This is the ONLY thing the build derives from the source about configuration, and it is a schema, not configuration:
//! no value, table, message or default is compiled in (the defaults are read from the plugin's files at run time, D17).
#[path = "build_support/keyscan.rs"]
mod keyscan;
#[path = "build_support/buildver.rs"]
mod buildver;
use std::path::Path;

fn main() {
    buildver::emit();
    let manifest = match std::env::var("CARGO_MANIFEST_DIR") {
        Ok(v) => v,
        Err(e) => {
            eprintln!("CARGO_MANIFEST_DIR: {e}");
            std::process::exit(1);
        }
    };
    let src = Path::new(&manifest).join("src");
    println!("cargo:rerun-if-changed={}", src.display());
    println!("cargo:rerun-if-changed={}", Path::new(&manifest).join("build_support").display());
    let keys = keyscan::scan(&src);
    let mut code = String::from(
        "// @generated by build.rs from the source; do not edit.\n/// The settings keys the source reads, sorted, with the type each read expects.\npub static REQUIRED: &[(&str, super::Kind)] = &[\n",
    );
    for (k, kind) in &keys {
        code.push_str(&format!("    ({k:?}, super::Kind::{}),\n", kind.name()));
    }
    code.push_str("];\n");
    let out_dir = match std::env::var("OUT_DIR") {
        Ok(v) => v,
        Err(e) => {
            eprintln!("OUT_DIR: {e}");
            std::process::exit(1);
        }
    };
    let out = Path::new(&out_dir).join("required_keys.rs");
    if let Err(e) = std::fs::write(&out, code) {
        eprintln!("write {}: {e}", out.display());
        std::process::exit(1);
    }
}
