#!/usr/bin/env node
// Prints plugins/anti-hall/engine/defaults/migrate_settings.toml: the slice of hooks/lib/settings-schema.js the settings forward-migration reads
// (every entry's section, key, type, bounds, default, env names, legacy file/key and plugin option), one JSON object per
// list item. tests/migrate_parity.rs compares this output with the committed file, so the engine's copy cannot drift.
//   node gen-migrate-schema.js [--repo <checkout>]
const path = require('path');
const i = process.argv.indexOf('--repo');
const REPO = path.resolve(i > 0 ? process.argv[i + 1] : path.join(__dirname, '..', '..'));
const schema = require(path.join(REPO, 'plugins/anti-hall/hooks/lib/settings-schema.js'));
const KEEP = ['section', 'key', 'type', 'default', 'min', 'max', 'exclusiveMin', 'rejectBelowMin', 'values', 'env', 'envAliases',
  'pluginOption', 'headline', 'homeOnly', 'locked', 'safetyDirection'];
const rows = schema.allSettings().map((e) => {
  const o = {};
  for (const k of KEEP) if (e[k] !== undefined && e[k] !== null) o[k] = e[k];
  if (e.legacy) { o.legacyFile = e.legacy.file; o.legacyKey = e.legacy.key; }
  return JSON.stringify(o);
});
const out = [];
out.push('# The settings schema as the settings forward-migration reads it (generated by parity/gen-migrate-schema.js from');
out.push('# plugins/anti-hall/hooks/lib/settings-schema.js; tests/migrate_parity.rs fails when the two differ). One JSON object per item.');
out.push('');
out.push('[migrate.settings_schema]');
out.push('doc = "Every settings entry the forward-migration of settings.json reads: section, key, type, bounds, default, environment names, legacy file and key, and plugin option."');
out.push('value = [');
for (const r of rows) out.push('  ' + JSON.stringify(r) + ',');
out.push(']');
process.stdout.write(out.join('\n') + '\n');
