#!/usr/bin/env node
// Prints plugins/anti-hall/engine/defaults/settings_cli.toml: the slice of hooks/lib/settings-schema.js the `ah-engine settings`
// command shows (section labels and descriptions, each setting's description, tier flags, safety note and default, null
// kept) and the NOT_TOGGLEABLE list. tests/it/operator_parity.rs compares this output with the committed file.
//   node gen-settings-cli.js [--repo <checkout>]
const path = require('path');
const i = process.argv.indexOf('--repo');
const REPO = path.resolve(i > 0 ? process.argv[i + 1] : path.join(__dirname, '..', '..'));
const schema = require(path.join(REPO, 'plugins/anti-hall/hooks/lib/settings-schema.js'));
const sections = schema.SECTIONS.map((s) => JSON.stringify({ key: s.key, label: s.label, description: s.description }));
const rows = schema.allSettings().map((e) => {
  const o = { section: e.section, key: e.key, type: e.type };
  if (e.default !== undefined) o.default = e.default;
  if (e.advanced) o.advanced = true;
  if (e.locked) o.locked = true;
  if (e.safetyNote !== undefined) o.safetyNote = e.safetyNote;
  if (e.description !== undefined) o.description = e.description;
  return JSON.stringify(o);
});
const nt = schema.NOT_TOGGLEABLE.map((n) => JSON.stringify({ name: n.name, reason: n.reason }));
const out = [];
out.push('# The settings schema as `ah-engine settings` shows it (generated by parity/gen-settings-cli.js from');
out.push('# plugins/anti-hall/hooks/lib/settings-schema.js; tests/it/operator_parity.rs fails when the two differ). One JSON object per item.');
out.push('');
const list = (name, doc, items) => {
  out.push('[settings_cli.' + name + ']');
  out.push('doc = ' + JSON.stringify(doc));
  out.push('value = [');
  for (const r of items) out.push('  ' + JSON.stringify(r) + ',');
  out.push(']');
  out.push('');
};
list('sections', 'The settings sections in display order: key, label, description.', sections);
list('items', 'Every setting with the fields `settings show` prints: type, default (null kept), advanced, locked, safetyNote and description.', rows);
list('not_toggleable', 'The parts of anti-hall that deliberately have no switch, with the reason `settings show` prints.', nt);
process.stdout.write(out.join('\n'));
