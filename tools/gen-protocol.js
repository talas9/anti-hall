#!/usr/bin/env node
'use strict';
// tools/gen-protocol.js — generate plugins/anti-hall/PROTOCOL.md, the FULL protocol text the compact
// injections point at, from the SAME arrays the hooks emit (plugins/anti-hall/hooks/verify-first-core.js),
// so the two cannot drift.
// Usage: node tools/gen-protocol.js          (rewrite PROTOCOL.md)
//        node tools/gen-protocol.js --check  (exit 1 when PROTOCOL.md is stale)
//        --out <file> targets another file (tests use it to prove --check detects drift)
// The compact core and ORCH_COMPACT send `<plugin root>/PROTOCOL.md` as an absolute path; the file
// ships with the plugin on both Claude Code and the Codex port (the Codex hooks run from the same root).

const fs = require('fs');
const path = require('path');

const PLUGIN = path.join(__dirname, '..', 'plugins', 'anti-hall');
const OUT = path.join(PLUGIN, 'PROTOCOL.md');
const core = require(path.join(PLUGIN, 'hooks', 'verify-first-core.js'));

function render() {
  const parts = [];
  parts.push('<!-- GENERATED by tools/gen-protocol.js from plugins/anti-hall/hooks/verify-first-core.js. Do not edit by hand: run `node tools/gen-protocol.js`. -->');
  parts.push('# anti-hall protocol (full text)\n');
  parts.push('The hooks send a compact form of this protocol with every load-bearing clause inline; this file holds the full wording, the reasoning behind each rule, and the parts that are only sent on demand. `context.protocolLevel=full` makes every channel send this text directly.\n');
  parts.push('## Core protocol (verify-first + root-cause)\n');
  parts.push(core.CORE_FULL.join('\n'));
  parts.push('\n## Disciplines vs skills\n');
  parts.push(core.DISCIPLINES_INDEX.join('\n'));
  parts.push('\n## Orchestration\n');
  parts.push('Rules A-N for the main thread (the coordinator). Claude Code sends this in full on the first Agent/Task/Workflow spawn of each context epoch (Codex and unconfirmed platforms: at SessionStart); the compact lines in the session context carry the letters A/E, B, L, G, M/N and K.\n');
  parts.push(core.ORCH_FULL);
  parts.push('\n### DevSwarm Primary only: rule W\n');
  parts.push(core.ORCH_DEVSWARM_PRIMARY);
  parts.push('\n## Subagent / worker rules\n');
  parts.push('What a spawned subagent receives (the orchestration rules above are deliberately omitted: a worker does the work itself).\n');
  parts.push(core.SUBAGENT_DISCIPLINES);
  parts.push('');
  parts.push(core.TEAMMATE_REPORTING_NOTE);
  parts.push('');
  parts.push('Inside a DevSwarm child workspace: ' + core.CHILD_WORKSPACE_MAILBOX_NOTE);
  return parts.join('\n') + '\n';
}

function main(argv) {
  const text = render();
  const oi = argv.indexOf('--out');
  const out = oi >= 0 ? path.resolve(argv[oi + 1]) : OUT;
  if (argv.includes('--check')) {
    let cur = null;
    try { cur = fs.readFileSync(out, 'utf8'); } catch (_) { /* missing */ }
    if (cur === text) { process.stdout.write('PROTOCOL.md is up to date\n'); return 0; }
    process.stderr.write('PROTOCOL.md is ' + (cur === null ? 'missing' : 'stale') + ': run `node tools/gen-protocol.js`\n');
    return 1;
  }
  fs.writeFileSync(out, text);
  process.stdout.write('wrote ' + path.relative(process.cwd(), out) + ' (' + text.length + ' chars)\n');
  return 0;
}

module.exports = { render, OUT };
if (require.main === module) process.exit(main(process.argv.slice(2)));
