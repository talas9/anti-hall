#!/usr/bin/env node
'use strict';
// tools/gen-agents-catalog.js — regenerate the condensed component catalog
// block in AGENTS.md (between the catalog markers) from the SAME sources the
// shipped code and llms.txt use, so the two cannot drift:
//   hooks      <- plugins/anti-hall/hooks/hooks.json (+ codex/hooks/hooks.json),
//                 one-line purpose from llms.txt's Hooks table
//   skills     <- plugins/anti-hall/skills/*/ and codex/skills/*/
//   CLI verbs  <- the dispatch switches of devswarm.js / settings.js /
//                 auto-handover-config.js, jev-report.js / jev-setup.js / defect.js
//   settings   <- plugins/anti-hall/hooks/lib/settings-schema.js
//   state      <- llms.txt's "State files" table
// Usage: node tools/gen-agents-catalog.js          (rewrite AGENTS.md in place)
//        node tools/gen-agents-catalog.js --check  (exit 1 when AGENTS.md is stale)
// tests/hygiene/agents-catalog.test.js runs the --check logic.

const fs = require('fs');
const path = require('path');

const REPO = path.join(__dirname, '..');
const P = (...p) => path.join(REPO, 'plugins', 'anti-hall', ...p);
const START = '<!-- catalog:start (generated by tools/gen-agents-catalog.js — do not edit by hand) -->';
const END = '<!-- catalog:end -->';

function read(rel) { return fs.readFileSync(path.join(REPO, rel), 'utf8'); }

function hookEvents(manifest) {
  const j = JSON.parse(fs.readFileSync(manifest, 'utf8'));
  const m = new Map();
  for (const [ev, groups] of Object.entries(j.hooks || {})) {
    for (const g of groups) for (const h of g.hooks || []) {
      const mm = /hooks\/([\w.-]+\.js)/.exec(h.command || '');
      if (!mm) continue;
      const k = mm[1];
      const tag = ev + (g.matcher ? '(' + g.matcher + ')' : '');
      if (!m.has(k)) m.set(k, []);
      if (!m.get(k).includes(tag)) m.get(k).push(tag);
    }
  }
  return m;
}

function llmsTable(title) {
  const src = read('llms.txt');
  const i = src.indexOf(title);
  if (i === -1) return [];
  const rows = [];
  for (const line of src.slice(i).split('\n').slice(1)) {
    if (/^## /.test(line)) break;
    if (!line.startsWith('|') || /^\|\s*-/.test(line) || /^\| (Event|Path|Skill|Codex skill|Setting)\b/.test(line)) continue;
    rows.push(line.split(/(?<!\\)\|/).slice(1, -1).map((c) => c.trim()));
  }
  return rows;
}

function shortPurpose(s) {
  let t = String(s || '').replace(/\\\|/g, '|').replace(/`/g, '');
  const cut = t.search(/[.;](\s|$)/);
  if (cut > 0) t = t.slice(0, cut);
  return t.length > 52 ? t.slice(0, 50).trimEnd() + '…' : t;
}

function switchVerbs(rel, header) {
  const src = read(rel);
  const a = src.indexOf(header);
  if (a === -1) return [];
  const b = src.indexOf('\nfunction ', a + header.length);
  const out = [];
  src.slice(a, b === -1 ? undefined : b).replace(/case '([a-z][a-z0-9-]*)':/g, (m, v) => { if (!out.includes(v)) out.push(v); return m; });
  return out;
}
function usageVerbs(rel, re) {
  const m = re.exec(read(rel));
  if (!m) return [];
  const out = [];
  for (const alt of m[1].split('|')) {
    const v = alt.trim().split(/\s/)[0];
    if (/^[a-z][a-z-]*$/.test(v) && !['on', 'off', 'shadow'].includes(v) && !out.includes(v)) out.push(v);
  }
  return out;
}

function fmt(v) { return v === null || v === undefined || v === '' ? '—' : (typeof v === 'string' ? v : JSON.stringify(v)); }

function build() {
  const out = [START, '', '## Component catalog (condensed; full detail in llms.txt)', ''];
  // Hooks
  const claude = hookEvents(P('hooks', 'hooks.json'));
  const codex = hookEvents(P('codex', 'hooks', 'hooks.json'));
  const purpose = new Map(llmsTable('## Hooks (').map((r) => [r[1], r[2]]));
  out.push('**Hooks** by event (script [C]=also on Codex: purpose):');
  const byEvent = new Map();
  for (const n of [...new Set([...claude.keys(), ...codex.keys()])]) {
    const ev = (claude.get(n) || codex.get(n)).join('+');
    if (!byEvent.has(ev)) byEvent.set(ev, []);
    byEvent.get(ev).push(n.replace(/\.js$/, '') + (codex.has(n) ? ' [C]' : '') + ': ' + shortPurpose(purpose.get(n) || ''));
  }
  for (const [ev, items] of byEvent) out.push('- ' + ev + ' — ' + items.join('; '));
  out.push('');
  // Skills
  const dirs = (d) => fs.readdirSync(d, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();
  out.push('**Skills** — Claude `/anti-hall:<name>`: ' + dirs(P('skills')).map((s) => '`' + s + '`').join(', ') + '.');
  out.push('Codex `anti-hall-<name>`: ' + dirs(P('codex', 'skills')).map((s) => s.replace(/^anti-hall-/, '')).join(', ') + '.');
  out.push('');
  // CLI verbs
  out.push('**CLI verbs**:');
  out.push('- `scripts/devswarm.js`: ' + switchVerbs('plugins/anti-hall/scripts/devswarm.js', 'function runArmed(').map((v) => '`' + v + '`').join(', ') + ' (`help <verb>` for detail).');
  out.push('- `scripts/settings.js`: ' + switchVerbs('plugins/anti-hall/scripts/settings.js', 'function main(').map((v) => '`' + v + '`').join(', ') + '; `scripts/auto-handover-config.js`: '
    + usageVerbs('plugins/anti-hall/scripts/auto-handover-config.js', /usage: auto-handover-config\.js ([^']+)'/).map((v) => '`' + v + '`').join(', ') + '.');
  out.push('- `scripts/jev-setup.js`: ' + usageVerbs('plugins/anti-hall/scripts/jev-setup.js', /usage: jev-setup\.js ([^'"`\n]+)/).map((v) => '`' + v + '`').join(', ')
    + '; `scripts/jev-report.js`: report (default), `label`, `prune-audit`; `scripts/defect.js`: `report`, `list`, `show`, `rule`, `archive`.');
  out.push('- `hooks/doctor.js [--repair]`; `skills/update/scripts/update.js [--check]`; `companion/devswarm-recover.js <id>` (the only kill path).');
  out.push('');
  // Settings
  const schema = require(P('hooks', 'lib', 'settings-schema.js'));
  out.push('**Settings** (`~/.anti-hall/settings.json`; env > file > /config > legacy > default; key=default; advanced keys after `|`, defaults via `settings.js show --all`):');
  for (const sec of schema.SECTIONS) {
    const head = sec.settings.filter((x) => !x.advanced).map((x) => x.key + '=' + fmt(x.default));
    const adv = sec.settings.filter((x) => x.advanced).map((x) => x.key);
    out.push('- ' + sec.key + ': ' + head.join(', ') + (adv.length ? ' | ' + adv.join(', ') : ''));
  }
  out.push('');
  // State files
  out.push('**State** (`~/.anti-hall/`): ' + llmsTable('## State files').map((r) => r[0].replace(/\\\|/g, '|')).join('; ') + '. Per project: `.anti-hall/progress/`, `history/`, `handovers/`.');
  out.push('');
  out.push('**Hard rules**: verify before claiming; no AI self-credit, no force-push; no data deletion without the user\'s explicit confirmation and never by an automated job; DevSwarm messaging via the mesh only; change settings via `/anti-hall:settings` only; skips only on the user\'s explicit request.');
  out.push('', END);
  return out.join('\n');
}

function current(src) {
  const a = src.indexOf(START);
  const b = src.indexOf(END);
  return a === -1 || b === -1 ? null : src.slice(a, b + END.length);
}

function apply(src, block) {
  const cur = current(src);
  if (cur) return src.replace(cur, block);
  return src.trimEnd() + '\n\n' + block + '\n';
}

if (require.main === module) {
  const file = path.join(REPO, 'AGENTS.md');
  const src = fs.readFileSync(file, 'utf8');
  const next = apply(src, build());
  if (process.argv.includes('--check')) {
    if (next !== src) { process.stderr.write('AGENTS.md catalog is stale — run node tools/gen-agents-catalog.js\n'); process.exit(1); }
    process.exit(0);
  }
  fs.writeFileSync(file, next);
  process.stdout.write('AGENTS.md catalog written (' + Buffer.byteLength(next) + ' bytes)\n');
}

module.exports = { build, apply, current, START, END };
